def get_synonym(keyword, page_id, avoid_original=True):
    if keyword not in keyword_synonyms:
        return keyword
    
    synonyms = keyword_synonyms[keyword]
    idx = page_id % len(synonyms)
    
    if avoid_original and synonyms[idx] == keyword:
        idx = (idx + 1) % len(synonyms)
    
    return synonyms[idx]

def replace_keyword_case_insensitive(text, keyword, page_id):
    if keyword not in keyword_synonyms:
        return text
    
    synonym = get_synonym(keyword, page_id, avoid_original=True)
    pattern = re.compile(re.escape(keyword), re.IGNORECASE)
    
    def replacer(match):
        original = match.group(0)
        if original[0].isupper():
            return synonym[0].upper() + synonym[1:]
        return synonym
    
    return pattern.sub(replacer, text)

